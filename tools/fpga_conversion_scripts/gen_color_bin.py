import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RGB_JSON = os.path.join(ROOT, "build", "oklch_rgb.json")
PALETTE_HEX = os.path.join(ROOT, "build", "palette.hex")
PALETTE_VH = os.path.join(ROOT, "build", "palette_pkg.vh")

def main():
    with open(RGB_JSON, "r") as f:
        rgb = json.load(f)

    r = rgb["r"]
    g = rgb["g"]
    b = rgb["b"]

    rgb24 = (r << 16) | (g << 8) | b

    # Kept for debugging/inspection (e.g. verify_palette.py) and for anyone
    # still using $readmemh at runtime.
    with open(PALETTE_HEX, "w") as f:
        f.write(f"{rgb24:06X}\n")

    # Synthesis-time constant. `top.v` `includes` this instead of loading a
    # register with $readmemh, so yosys can fully constant-fold the palette
    # away rather than spending LUTs/DFFs/mux logic on a value that never
    # changes at runtime. This matters here because the 325 MHz shift-clock
    # domain is already timing-marginal on ECP5 -6; every bit of avoidable
    # logic near it helps.
    with open(PALETTE_VH, "w") as f:
        f.write("// Auto-generated by gen_color_bin.py -- do not edit by hand.\n")
        f.write(f"// Source: {os.path.relpath(RGB_JSON, ROOT)}\n")
        f.write(f"localparam [23:0] PALETTE_WHITE = 24'h{rgb24:06X};\n")

    print(f"Generated palette.hex and palette_pkg.vh with RGB = ({r}, {g}, {b})")

if __name__ == "__main__":
    main()