// *** Read docs/TIMING_NOTES.md before changing anything in this file's
// *** clocking/timing/serializer section (h_cnt/v_cnt limits, the
// *** clk_shift-domain always block, or the ODDRX1F instances). The
// *** shift clock is fixed at exactly 5x the pixel clock by the serializer;
// *** changing resolution without also retuning pll.v will break the video
// *** output. At 800x600 the shift clock is 200 MHz, which has plenty of
// *** margin on ECP5 -6.
// ***
// *** The palette include below (palette_pkg.vh) is a build-time constant
// *** on purpose -- see TIMING_NOTES.md #4 before changing it back to a
// *** $readmemh-loaded register.
// ***
// *** STEP 1 of the spatial-thinking OS: the 640x480 "work surface" is now
// *** a movable/hideable window, driven by the onboard buttons, using a
// *** ternary (-1/0/+1) position model instead of an adder-based cursor.
// *** See the "window position trits" section below.
module top (
    input  wire       clk_25mhz,
    input  wire [6:0] btn,         // [0]=PWR(unused,active-low) [1]=FIRE1
                                    // [2]=FIRE2 [3]=UP [4]=DOWN [5]=LEFT [6]=RIGHT
    output wire [3:0] gpdi_dp      // [0]=blue [1]=green [2]=red [3]=clock
);
    // ---------- clocks ----------
    wire clk_shift, clk_pixel, locked;
    pll pll_i (.clkin(clk_25mhz), .clkout0(clk_shift),
               .clkout1(clk_pixel), .locked(locked));

    // ---------- external palette (OKLCH->RGB result) ----------
    // Generated by tools/fpga_conversion_scripts/gen_color_bin.py from
    // data/oklch/theme.ini. This is a build-time constant (it only changes
    // when you rerun the python step and resynthesize), so it's pulled in
    // as a `localparam via `include rather than loaded into a register with
    // $readmemh at run time. That lets yosys constant-fold it away instead
    // of spending real LUTs/DFFs/muxes on it.
    `include "../build/palette_pkg.vh"

    wire [7:0] desk_r = PALETTE_WHITE[23:16];  // "white" now themed via theme.ini
    wire [7:0] desk_g = PALETTE_WHITE[15:8];
    wire [7:0] desk_b = PALETTE_WHITE[7:0];

    // ---------- 800x600 @ 60 Hz timing (VESA, 40 MHz pixel clock) ----------
    // Both syncs are POSITIVE polarity for this mode.
    localparam H_ACTIVE = 800, H_FRONT = 40, H_SYNC = 128, H_BACK = 88;
    localparam V_ACTIVE = 600, V_FRONT = 1,  V_SYNC = 4,   V_BACK = 23;

    localparam H_TOTAL      = H_ACTIVE + H_FRONT + H_SYNC + H_BACK;  // 1056
    localparam V_TOTAL      = V_ACTIVE + V_FRONT + V_SYNC + V_BACK;  // 628
    localparam H_SYNC_START = H_ACTIVE + H_FRONT;                    // 840
    localparam H_SYNC_END   = H_SYNC_START + H_SYNC;                 // 968
    localparam V_SYNC_START = V_ACTIVE + V_FRONT;                    // 601
    localparam V_SYNC_END   = V_SYNC_START + V_SYNC;                 // 605

    reg [10:0] h_cnt = 0;
    reg [10:0] v_cnt = 0;

    always @(posedge clk_pixel) begin
        if (h_cnt == H_TOTAL - 1) begin
            h_cnt <= 0;
            if (v_cnt == V_TOTAL - 1) v_cnt <= 0;
            else                      v_cnt <= v_cnt + 1;
        end else begin
            h_cnt <= h_cnt + 1;
        end
    end

    wire h_active = (h_cnt < H_ACTIVE);
    wire v_active = (v_cnt < V_ACTIVE);
    wire hsync    =  (h_cnt >= H_SYNC_START && h_cnt < H_SYNC_END);
    wire vsync    =  (v_cnt >= V_SYNC_START && v_cnt < V_SYNC_END);
    wire blank    = ~(h_active && v_active);

    // ======================================================================
    // Window position trits -- the ternary spatial model
    // ======================================================================
    // Trit encoding: 2 wires {n,p}, never both 1.
    //   -1 = 10 (n)      0 = 00 (zero)      +1 = 01 (p)
    // Negating a trit is just swapping the two wires -- no ALU needed.
    localparam [1:0] TRIT_ZERO = 2'b00;
    localparam [1:0] TRIT_POS  = 2'b01;
    localparam [1:0] TRIT_NEG  = 2'b10;

    // ---- button synchronizer + rising-edge (press) detector ----
    // All buttons on this board are active-high except btn[0] (power,
    // unused here). Two-flop synchronizer, then edge-detect against the
    // previous synchronized sample -- this is all in the clk_pixel domain,
    // which has enormous timing margin (see TIMING_NOTES.md #5).
    reg [6:0] btn_sync0 = 0, btn_sync1 = 0, btn_prev = 0;
    always @(posedge clk_pixel) begin
        btn_sync0 <= btn;
        btn_sync1 <= btn_sync0;
        btn_prev  <= btn_sync1;
    end
    wire [6:0] press = btn_sync1 & ~btn_prev; // one-cycle pulse on button-down

    wire press_fire1 = press[1]; // recenter
    wire press_fire2 = press[2]; // show/hide toggle
    wire press_up    = press[3];
    wire press_down  = press[4];
    wire press_left  = press[5];
    wire press_right = press[6];

    // ---- position trits: (x, y) relative to center ----
    // x: -1=Left, 0=Center, +1=Right   y: -1=Down, 0=Center, +1=Up
    // Each press SETS the trit directly (a register write to one of three
    // fixed states), it does not increment/accumulate a coordinate.
    reg [1:0] pos_x = TRIT_ZERO;
    reg [1:0] pos_y = TRIT_ZERO;
    reg       win_visible = 1'b1;

    always @(posedge clk_pixel) begin
        if (press_left)  pos_x <= TRIT_NEG;
        if (press_right) pos_x <= TRIT_POS;
        if (press_up)    pos_y <= TRIT_POS;
        if (press_down)  pos_y <= TRIT_NEG;
        if (press_fire1) begin
            pos_x <= TRIT_ZERO;
            pos_y <= TRIT_ZERO;
        end
        if (press_fire2) win_visible <= ~win_visible;
    end

    // ---- window size (fixed for step 1; trit-driven scaling is step 2) ----
    localparam WORK_W = 640;
    localparam WORK_H = 480;
    localparam [23:0] WORK_RGB = 24'h000060; // dark blue, hard-coded for now

    // ---- trit -> pixel anchor lookup (a mux, not an adder) ----
    function [10:0] anchor_x;
        input [1:0] t;
        begin
            case (t)
                TRIT_NEG: anchor_x = 0;                   // Left
                TRIT_POS: anchor_x = H_ACTIVE - WORK_W;   // Right
                default:  anchor_x = (H_ACTIVE - WORK_W) / 2; // Center
            endcase
        end
    endfunction

    function [10:0] anchor_y;
        input [1:0] t;
        begin
            case (t)
                TRIT_POS: anchor_y = 0;                   // Up
                TRIT_NEG: anchor_y = V_ACTIVE - WORK_H;   // Down
                default:  anchor_y = (V_ACTIVE - WORK_H) / 2; // Center
            endcase
        end
    endfunction

    wire [10:0] work_x0 = anchor_x(pos_x);
    wire [10:0] work_y0 = anchor_y(pos_y);

    wire in_work = win_visible &&
                   (h_cnt >= work_x0) && (h_cnt < work_x0 + WORK_W) &&
                   (v_cnt >= work_y0) && (v_cnt < work_y0 + WORK_H);

    wire [7:0] pix_r = in_work ? WORK_RGB[23:16] : desk_r;
    wire [7:0] pix_g = in_work ? WORK_RGB[15:8]  : desk_g;
    wire [7:0] pix_b = in_work ? WORK_RGB[7:0]   : desk_b;

    // ---------- TMDS encoding ----------
    wire [9:0] tmds_b, tmds_g, tmds_r;
    tmds_encoder enc_b (.clk(clk_pixel), .data(pix_b), .c({vsync, hsync}), .blank(blank), .encoded(tmds_b));
    tmds_encoder enc_g (.clk(clk_pixel), .data(pix_g), .c(2'b00),          .blank(blank), .encoded(tmds_g));
    tmds_encoder enc_r (.clk(clk_pixel), .data(pix_r), .c(2'b00),          .blank(blank), .encoded(tmds_r));

    // ---------- pixel-clock toggle, used to lock the shift phase ----------
    reg ptog = 0;
    always @(posedge clk_pixel) ptog <= ~ptog;

    // ---------- 10:2 serializer at 5x pixel clock (200 MHz) ----------
    reg       t1 = 0, t2 = 0;
    reg [4:0] ring = 5'b00001;
    reg [9:0] sr_b = 0, sr_g = 0, sr_r = 0, sr_c = 0;
    wire detect = (t1 != t2);

    always @(posedge clk_shift) begin
        t1 <= ptog;
        t2 <= t1;

        // one-hot ring, re-locked to the pixel clock every pixel
        if (detect) ring <= 5'b00001;
        else        ring <= {ring[3:0], ring[4]};

        if (ring[0]) begin
            sr_b <= tmds_b;
            sr_g <= tmds_g;
            sr_r <= tmds_r;
            sr_c <= 10'b0000011111;
        end else begin
            sr_b <= {2'b00, sr_b[9:2]};
            sr_g <= {2'b00, sr_g[9:2]};
            sr_r <= {2'b00, sr_r[9:2]};
            sr_c <= {2'b00, sr_c[9:2]};
        end
    end

    ODDRX1F ddr_b (.SCLK(clk_shift), .RST(1'b0), .D0(sr_b[0]), .D1(sr_b[1]), .Q(gpdi_dp[0]));
    ODDRX1F ddr_g (.SCLK(clk_shift), .RST(1'b0), .D0(sr_g[0]), .D1(sr_g[1]), .Q(gpdi_dp[1]));
    ODDRX1F ddr_r (.SCLK(clk_shift), .RST(1'b0), .D0(sr_r[0]), .D1(sr_r[1]), .Q(gpdi_dp[2]));
    ODDRX1F ddr_c (.SCLK(clk_shift), .RST(1'b0), .D0(sr_c[0]), .D1(sr_c[1]), .Q(gpdi_dp[3]));
endmodule